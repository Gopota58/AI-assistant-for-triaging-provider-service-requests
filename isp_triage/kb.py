def retrieve(claim: Claim, action: int, top_k: int = 2) -> List[dict]:
    """Подбирает документы БЗ по совпадению ключевых слов и классу действия."""
    text = claim.text.lower()
    scored = []
    for d in DOCS:
        score = sum(1 for k in d["kw"] if k in text)
        if action == 2 and d["id"] in ("REG-114", "MAN-ONT", "REG-330", "REG-500", "REG-620"):
            score += 0.5
        if action == 0 and d["id"] in ("REG-201", "REG-410"):
            score += 0.5
        if action == 1 and d["id"] in ("REG-201", "REG-410"):
            score += 0.3
        if score > 0:
            scored.append((score, d))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [d for _, d in scored[:top_k]]
